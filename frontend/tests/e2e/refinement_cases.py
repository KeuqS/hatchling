    def test_75_data_import_is_reviewed_then_exported_as_a_real_local_file(self):
        self.open_settings()
        self.page.get_by_role('button', name='Data controls', exact=True).click()
        self.page.get_by_role('button', name='Import memory', exact=True).click()
        modal = self.page.get_by_role('dialog', name='Import memory', exact=True)
        modal.locator('input[type=file]').set_input_files({'name': 'reviewed-note.md', 'mimeType': 'text/markdown', 'buffer': b'# Planning\nKeep Friday free.'})
