    def test_67_settings_breathing_room_and_bottom_tooltip_are_safe(self):
        self.page.set_viewport_size({'width': 1174, 'height': 838})
        self.open_settings()
        dialog = self.page.get_by_role('dialog', name='Settings', exact=True)
        account = dialog.locator('.account-card')
        self.assertGreaterEqual(account.bounding_box()['y'] - dialog.bounding_box()['y'], 48)
        close = dialog.get_by_role('button', name='Close Settings', exact=True)
        self.viewport_contains(close, 20)
        avatar = self.page.get_by_role('radio', name='Match my avatar', exact=True)
        avatar.hover()
        tip = self.page.get_by_role('tooltip')
        expect(tip).to_be_visible()
        self.viewport_contains(tip, 8)
        self.assertLess(tip.bounding_box()['y'], avatar.bounding_box()['y'])
