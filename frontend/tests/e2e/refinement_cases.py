        with self.page.expect_download() as pending:
            self.page.get_by_role('button', name='Download your agent data', exact=True).click()
        data = json.loads(Path(pending.value.path()).read_text())
        self.assertIn('Reviewed import', json.dumps(data))
        self.assertIn('Keep Friday free.', json.dumps(data))

