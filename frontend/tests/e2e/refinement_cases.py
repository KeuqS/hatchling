class RefinementCases:
    def soul(self):
        self.page.get_by_role('tab', name='Identity', exact=True).click()
        self.page.get_by_role('button', name='Open SOUL', exact=True).click()
        return self.page.get_by_role('dialog', name='SOUL.md', exact=True)

    def viewport_contains(self, locator, inset=0):
        box = locator.bounding_box()
        self.assertIsNotNone(box)
        view = self.page.viewport_size
        self.assertGreaterEqual(box['x'], inset - 1)
        self.assertGreaterEqual(box['y'], inset - 1)
        self.assertLessEqual(box['x'] + box['width'], view['width'] - inset + 1)
        self.assertLessEqual(box['y'] + box['height'], view['height'] - inset + 1)

    def test_63_activity_is_centered_and_large_at_three_viewport_sizes(self):
        dialog = self.rich_activity()
        for width, height in [(1569, 931), (1174, 838), (900, 560)]:
            self.page.set_viewport_size({'width': width, 'height': height})
            box = dialog.bounding_box()
            self.assertAlmostEqual(box['x'] + box['width']/2, width/2, delta=1)
            self.assertAlmostEqual(box['y'] + box['height']/2, height/2, delta=1)
            self.assertGreater(box['width'], width * .8)
            self.assertGreater(box['height'], height * .8)
            self.viewport_contains(dialog.locator('.dialog-header'), 16)
            self.viewport_contains(dialog.get_by_role('button', name='Close Review sample document collection', exact=True), 16)
        self.assert_no_overflow()

    def test_64_tab_indicator_is_persistent_and_moves_between_rapid_selections(self):
        self.page.emulate_media(reduced_motion='no-preference')
        indicator = self.page.locator('.context-tab-indicator')
        handle = indicator.element_handle()
        tabs = self.page.locator('.context-tabs')
        start = indicator.bounding_box()['x']
        tabs.get_by_role('tab', name='Activity', exact=True).click()
        self.assertTrue(handle.evaluate('(node) => node === document.querySelector(".context-tab-indicator")'))
        self.page.wait_for_timeout(90)
        during = indicator.bounding_box()['x']
        self.assertLess(during, start)
        self.page.wait_for_timeout(250)
        self.assertLess(indicator.bounding_box()['x'], during)
        tabs.get_by_role('tab', name='Schedule', exact=True).click()
        tabs.get_by_role('tab', name='Identity', exact=True).click()
        self.page.wait_for_timeout(300)
        selected = tabs.get_by_role('tab', name='Identity', exact=True)
        self.assertAlmostEqual(indicator.bounding_box()['x'], selected.bounding_box()['x'], delta=1)
        expect(selected).to_have_attribute('aria-selected', 'true')
        self.assertTrue(handle.evaluate('(node) => node.isConnected'))

