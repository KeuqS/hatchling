        # window, scrolls; both the top card and last control remain reachable.
        pane.evaluate('(el) => el.scrollTop = el.scrollHeight')
        last = dialog.get_by_role('radio', name='Large', exact=True)
        self.viewport_contains(last, 20)
        self.assertLess(last.bounding_box()['y'] + last.bounding_box()['height'], dialog.bounding_box()['y'] + dialog.bounding_box()['height'] - 16)
