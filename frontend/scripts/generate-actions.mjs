// The command union is the sole source of machine-readable argument shapes.
import ts from 'typescript';
import { writeFileSync, readFileSync } from 'node:fs';
const program = ts.createProgram(['src/protocol/models.ts'], { strict: true, target: ts.ScriptTarget.ES2022 });
const checker = program.getTypeChecker();
const source = program.getSourceFile('src/protocol/models.ts');
const declaration = source?.statements.find(node => ts.isTypeAliasDeclaration(node) && node.name.text === 'Command');
if (!declaration)
    throw new Error('Command union is missing.');
const union = checker.getTypeAtLocation(declaration);
if (!union.isUnion())
    throw new Error('Command must remain a discriminated union.');
const schemaField = type => {
    const parts = (type.isUnion() ? type.types : [type]).filter(part => !(part.flags & ts.TypeFlags.Undefined));
    if (parts.every(part => part.flags & ts.TypeFlags.StringLiteral))
        return { type: 'string', enum: parts.map(part => part.value) };
    if (parts.every(part => part.flags & ts.TypeFlags.StringLike))
        return { type: 'string' };
    if (parts.every(part => part.flags & ts.TypeFlags.NumberLike))
        return { type: 'number' };
    if (parts.every(part => part.flags & ts.TypeFlags.BooleanLike))
        return { type: 'boolean' };
    throw new Error(`Unmapped command argument: ${checker.typeToString(type)}`);
};
const schemas = {};
for (const variant of union.types) {
    const properties = {};
    const required = [];
    for (const property of variant.getProperties()) {
        properties[property.name] = schemaField(checker.getTypeOfSymbolAtLocation(property, declaration));
        if (!(property.flags & ts.SymbolFlags.Optional))
            required.push(property.name);
    }
    for (const name of properties.type.enum)
        schemas[name] = { type: 'object', properties: { ...properties, type: { type: 'string', enum: [name] } }, required, additionalProperties: false };
}
if (process.argv.includes('--check')) {
    const current = ts.createSourceFile('command-schemas.ts', readFileSync('src/automation/command-schemas.ts', 'utf8'), ts.ScriptTarget.Latest, true);
    const variable = current.statements.filter(ts.isVariableStatement).flatMap(statement => statement.declarationList.declarations).find(item => item.name.getText(current) === 'commandSchemas');
    if (!variable?.initializer || JSON.stringify(JSON.parse(variable.initializer.getText(current))) !== JSON.stringify(schemas))
        throw new Error('Agent action schemas drifted. Run npm run actions:generate.');
    console.log(`${Object.keys(schemas).length} command schemas match the strict TypeScript union.`);
}
else {
    writeFileSync('src/automation/command-schemas.ts', `// Generated by scripts/generate-actions.mjs. Edit protocol/models.ts, not this file.\nimport type { Command } from '../protocol/models.js';\nimport type { ActionSchema } from './contracts.js';\nexport const commandSchemas: Readonly<Record<Command['type'], ActionSchema>> = ${JSON.stringify(schemas, null, 2)};\n`);
    console.log(`${Object.keys(schemas).length} command schemas generated.`);
}
