#!/usr/bin/env python3
"""Generate the x86_64 syscall name->number table for the adversarial suite.

Reads the kernel headers on THIS machine
(/usr/include/x86_64-linux-gnu/asm/unistd_64.h) and emits
crates/hatchling-adversarial/src/syscall_table.rs.

The committed table is the universe the adversarial suite's seccomp
catalog is drawn from: the catalog is computed at runtime as
(table minus SeccompProfile::agent()'s allowlist), so the catalog can
never drift from the allowlist. The table itself can go stale when the
kernel headers change; a unit test in the adversarial crate re-parses
the live headers and fails loudly when the table lacks a number (or a
name) they define, pointing back here. Run this on the machine with the
newest headers: that table is a superset and passes everywhere.

Never hand-write syscall numbers: a wrong number is a silent hole and
a live SIGSYS (the lesson that produced the portable seccomp_startup
test). Regenerate from headers, always.
"""

import re
import sys
from pathlib import Path

HEADER = "/usr/include/x86_64-linux-gnu/asm/unistd_64.h"
OUT = (
    Path(__file__).resolve().parent.parent
    / "crates"
    / "hatchling-adversarial"
    / "src"
    / "syscall_table.rs"
)

DEFINE_RE = re.compile(r"^#define\s+__NR_([A-Za-z0-9_]+)\s+([0-9]+)\s*$")


def main() -> None:
    header = Path(HEADER)
    if not header.is_file():
        sys.exit(f"error: kernel header not found: {HEADER}")
    entries: dict[int, str] = {}
    for line in header.read_text().splitlines():
        m = DEFINE_RE.match(line.strip())
        if m:
            name, nr = m.group(1), int(m.group(2))
            # One nr can carry an alias (rare); first name wins, aliases
            # are dropped so the table stays a function nr -> name.
            entries.setdefault(nr, name)
    if not entries:
        sys.exit(f"error: no __NR_ defines parsed from {HEADER}")
    lines = [
        "//! `x86_64` syscall name -> number table, generated from the",
        "//! kernel headers — DO NOT EDIT BY HAND.",
        f"//!",
        f"//! Source: {HEADER}",
        f"//! Generated by: `scripts/gen_seccomp_catalog.py`",
        "//!",
 "//! The adversarial suite computes its denied-syscall",
        "//! catalog as this table minus `SeccompProfile::agent()`'s",
        "//! allowlist, so the catalog is structurally synchronized 1:1",
        "//! with the allowlist's complement. Regenerate (and re-run the",
        "//! suite) when the headers change.",
        "",
        "/// One row of the syscall table: the kernel's name and number.",
        "pub(crate) struct SyscallRow {",
        "    /// Name as spelled in the kernel headers (`read`, `openat`).",
        "    pub(crate) name: &'static str,",
        "    /// `x86_64` syscall number.",
        "    pub(crate) nr: u32,",
        "}",
        "",
        "/// Every syscall number the kernel headers define, sorted by number.",
        "pub(crate) const SYSCALL_TABLE: &[SyscallRow] = &[",
    ]
    for nr in sorted(entries):
        lines.append(f'    SyscallRow {{ name: "{entries[nr]}", nr: {nr} }},')
    lines += ["];", ""]
    OUT.write_text("\n".join(lines))
    print(f"wrote {OUT} ({len(entries)} syscalls)")


if __name__ == "__main__":
    main()
